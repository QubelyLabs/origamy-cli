#!/usr/bin/env bash
# Regenerate cmd/origamy/cmd/bundle_hashes.go: the sha256 of every version of
# each BYOD bundle file the control plane has ever served from
# dashboard/public/byod/, taken from its git history (every branch and tag the
# checkout knows). `origamy upgrade` treats a Docker project file matching one
# of them as unedited, so a project deployed before the CLI wrote
# .origamy-bundle.json can still be refreshed safely. Re-run it whenever the
# control plane's bundle changes (scripts/sync-byod-bundle.sh there), after a
# `git fetch --all` in that checkout.
#
#   scripts/gen-bundle-hashes.sh                         # sibling checkout ../control-plane
#   scripts/gen-bundle-hashes.sh /path/to/origamy-control-plane
#   scripts/gen-bundle-hashes.sh /path/to/origamy-control-plane -   # print, don't write
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CP="${1:-$HERE/../control-plane}"
OUT="${2:-$HERE/cmd/origamy/cmd/bundle_hashes.go}"

git -C "$CP" rev-parse --git-dir >/dev/null 2>&1 || { echo "error: $CP is not a control-plane git checkout" >&2; exit 1; }

# Same order as bundleFiles in cmd/origamy/cmd/bundle.go.
FILES="docker-compose.yml clickhouse-init.sql clickhouse-users.xml Caddyfile"

render() {
  echo "// Code generated by scripts/gen-bundle-hashes.sh; DO NOT EDIT."
  echo
  echo "package cmd"
  echo
  echo "// knownBundleHashes is the sha256 of every version of each bundle file the"
  echo "// control plane has served (dashboard/public/byod/ in its git history),"
  echo "// oldest first, with the date and commit that introduced it."
  echo "var knownBundleHashes = map[string][]string{"
  for f in $FILES; do
    path="dashboard/public/byod/$f"
    echo "\"$f\": {"
    seen=" "
    # --reverse: oldest first. A commit that deleted the file has no blob at
    # the path and is skipped; a blob served by several commits is listed once.
    git -C "$CP" log --all --reverse --format='%H %ad' --date=short -- "$path" | while read -r sha date; do
      blob="$(git -C "$CP" rev-parse -q --verify "$sha:$path" 2>/dev/null)" || continue
      case "$seen" in *" $blob "*) continue ;; esac
      seen="$seen$blob "
      sum="$(git -C "$CP" cat-file blob "$blob" | shasum -a 256 | cut -d' ' -f1)"
      echo "\"$sum\", // $date ${sha:0:7}"
    done
    echo "},"
  done
  echo "}"
}

if [ "$OUT" = "-" ]; then
  render | gofmt
else
  tmp="$(mktemp "$OUT.XXXXXX")"
  trap 'rm -f "$tmp"' EXIT
  render | gofmt >"$tmp"
  mv "$tmp" "$OUT"
  echo "wrote $OUT from $CP"
fi
