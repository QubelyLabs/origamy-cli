#!/usr/bin/env bash
# Regenerate cmd/origamy/cmd/bundle_hashes.go: the sha256 of every version of
# each BYOD bundle file the control plane has ever served from
# dashboard/public/byod/, taken from its git history (every branch and tag the
# checkout knows), and the data-plane release(s) it handed out with each.
# `origamy upgrade` treats a Docker project file matching one of them as
# unedited, so a project deployed before the CLI wrote .origamy-bundle.json can
# still be refreshed safely, and names its backup after that release. Re-run
# it whenever the control plane's bundle or its release pin changes
# (scripts/sync-byod-bundle.sh there), after a `git fetch --all` in that
# checkout.
#
#   scripts/gen-bundle-hashes.sh                         # sibling checkout ../control-plane
#   scripts/gen-bundle-hashes.sh /path/to/origamy-control-plane
#   scripts/gen-bundle-hashes.sh /path/to/origamy-control-plane -   # print, don't write
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CP="${1:-$HERE/../control-plane}"
OUT="${2:-$HERE/cmd/origamy/cmd/bundle_hashes.go}"

git -C "$CP" rev-parse --git-dir >/dev/null 2>&1 || { echo "error: $CP is not a control-plane git checkout" >&2; exit 1; }

# Same order as bundleFiles in cmd/origamy/cmd/bundle.go.
FILES="docker-compose.yml clickhouse-init.sql clickhouse-users.xml Caddyfile"
BYOD="dashboard/public/byod"
HANDLERS="internal/api/byod_handlers.go"

PAIRS="$(mktemp)"
trap 'rm -f "$PAIRS" "${tmp:-}"' EXIT

# release_at <commit>: the data-plane release the control plane handed out at
# that commit: byodDataPlaneRelease, or before that constant existed the fixed
# DP_IMAGE_TAG its Docker handoff wrote (main). Empty when neither is there.
release_at() {
  local src rel
  src="$(git -C "$CP" show "$1:$HANDLERS" 2>/dev/null)" || return 0
  rel="$(printf '%s\n' "$src" | sed -n 's/^const byodDataPlaneRelease = "\(.*\)"$/\1/p')"
  [ -n "$rel" ] || rel="$(printf '%s\n' "$src" | grep -o 'DP_IMAGE_TAG=[0-9A-Za-z][0-9A-Za-z._-]*' | head -1 | cut -d= -f2 || true)"
  printf '%s' "$rel"
}

# Every (sha256, release) pair that existed together in some commit. Any such
# pair shows up at a commit touching the bundle or the pin, merges included
# (--full-history), since in between neither changes.
sums=" "
git -C "$CP" log --all --full-history --format='%H' -- "$BYOD" "$HANDLERS" | while read -r sha; do
  rel="$(release_at "$sha")"
  [ -n "$rel" ] || continue
  for f in $FILES; do
    blob="$(git -C "$CP" rev-parse -q --verify "$sha:$BYOD/$f" 2>/dev/null)" || continue
    case "$sums" in
    *" $blob="*) sum="${sums#*" $blob="}"; sum="${sum%% *}" ;;
    *) sum="$(git -C "$CP" cat-file blob "$blob" | shasum -a 256 | cut -d' ' -f1)"; sums="$sums$blob=$sum " ;;
    esac
    echo "$sum $rel"
  done
done | sort -u >"$PAIRS"

# releases_of <sum>: its releases as Go string literals, moving tags (main)
# first, then numbered releases in version order.
releases_of() {
  awk -v s="$1" '$1 == s { print $2 }' "$PAIRS" |
    awk -F. '{ if ($0 ~ /^[0-9]+\.[0-9]+\.[0-9]+$/) printf "1 %010d %010d %010d %s\n", $1, $2, $3, $0; else printf "0 0 0 0 %s\n", $0 }' |
    sort | awk '{ printf "%s\"%s\"", (NR > 1 ? ", " : ""), $5 }'
}

render() {
  echo "// Code generated by scripts/gen-bundle-hashes.sh; DO NOT EDIT."
  echo
  echo "package cmd"
  echo
  echo "// knownBundleHashes is the sha256 of every version of each bundle file the"
  echo "// control plane has served (dashboard/public/byod/ in its git history),"
  echo "// oldest first, with the date and commit that introduced it."
  echo "var knownBundleHashes = map[string][]string{"
  for f in $FILES; do
    path="$BYOD/$f"
    echo "\"$f\": {"
    seen=" "
    # --reverse: oldest first. A commit that deleted the file has no blob at
    # the path and is skipped; a blob served by several commits is listed once.
    git -C "$CP" log --all --reverse --format='%H %ad' --date=short -- "$path" | while read -r sha date; do
      blob="$(git -C "$CP" rev-parse -q --verify "$sha:$path" 2>/dev/null)" || continue
      case "$seen" in *" $blob "*) continue ;; esac
      seen="$seen$blob "
      sum="$(git -C "$CP" cat-file blob "$blob" | shasum -a 256 | cut -d' ' -f1)"
      echo "\"$sum\", // $date ${sha:0:7}"
    done
    echo "},"
  done
  echo "}"
  echo
  echo "// knownBundleReleases maps each of those versions to the data-plane releases"
  echo "// the control plane handed out while it served it (byodDataPlaneRelease, or"
  echo "// the DP_IMAGE_TAG its Docker handoff wrote before that existed), moving"
  echo "// tags first, then numbered releases in order."
  echo "var knownBundleReleases = map[string][]string{"
  for f in $FILES; do
    echo "// $f"
    seen=" "
    git -C "$CP" log --all --reverse --format='%H' -- "$BYOD/$f" | while read -r sha; do
      blob="$(git -C "$CP" rev-parse -q --verify "$sha:$BYOD/$f" 2>/dev/null)" || continue
      case "$seen" in *" $blob "*) continue ;; esac
      seen="$seen$blob "
      sum="$(git -C "$CP" cat-file blob "$blob" | shasum -a 256 | cut -d' ' -f1)"
      rels="$(releases_of "$sum")"
      if [ -n "$rels" ]; then echo "\"$sum\": {$rels},"; fi
    done
  done
  echo "}"
}

if [ "$OUT" = "-" ]; then
  render | gofmt
else
  tmp="$(mktemp "$OUT.XXXXXX")"
  render | gofmt >"$tmp"
  mv "$tmp" "$OUT"
  echo "wrote $OUT from $CP"
fi
